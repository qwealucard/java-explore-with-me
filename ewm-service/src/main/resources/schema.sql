
CREATE TABLE IF NOT EXISTS categories (
  id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS compilations (
  id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  title VARCHAR(100) NOT NULL,
  pinned VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(100) NOT NULL,
  name VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS locations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lat DOUBLE NOT NULL,
  lon DOUBLE NOT NULL
);

CREATE TABLE IF NOT EXISTS events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  annotation VARCHAR(255) NOT NULL,
  paid BOOLEAN NOT NULL DEFAULT FALSE,
  title VARCHAR(100) NOT NULL,
  event_date DATE NOT NULL,
  description VARCHAR(255) NOT NULL,
  request_moderation BOOLEAN NOT NULL DEFAULT TRUE,
  participant_limit INTEGER DEFAULT 0,
  published_on DATE,
  created_on DATE NOT NULL,
  category_id BIGINT REFERENCES categories(id) ON DELETE RESTRICT,
  user_id BIGINT REFERENCES users(id) ON DELETE RESTRICT,
  location_id BIGINT REFERENCES locations(id) ON DELETE RESTRICT,
  state VARCHAR(100) NOT NULL,
  confirmed_requests BIGINT NOT NULL DEFAULT 0,
  views BIGINT
);

CREATE TABLE IF NOT EXISTS compilations_events (
  compilations_id BIGINT REFERENCES compilations(id) ON DELETE CASCADE,
  event_id BIGINT REFERENCES events(id) ON DELETE CASCADE,
  PRIMARY KEY (compilations_id, event_id)
);

CREATE TABLE IF NULL EXISTS requests(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created DATE NOT NULL,
  event_id BIGINT REFERENCES events(id) NOT NULL,
  requester_id BIGINT REFERENCES users(id) NOT NULL,
  status VARCHAR(100) NOT NULL
);