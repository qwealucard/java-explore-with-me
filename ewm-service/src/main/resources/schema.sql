DROP TABLE if EXISTS categories CASCADE;
DROP TABLE if EXISTS compilations CASCADE;
DROP TABLE if EXISTS users CASCADE;
DROP TABLE if EXISTS locations CASCADE;
DROP TABLE if EXISTS events CASCADE;
DROP TABLE if EXISTS compilations_events CASCADE;
DROP TABLE if EXISTS requests CASCADE;

CREATE TABLE IF NOT EXISTS categories (
  id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS compilations (
  id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  pinned BOOLEAN NOT NULL
);

CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL,
  name TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS locations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lat float NOT NULL,
  lon float NOT NULL
);

CREATE TABLE IF NOT EXISTS events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  annotation TEXT NOT NULL,
  paid BOOLEAN DEFAULT FALSE,
  title TEXT NOT NULL,
  event_date TIMESTAMP NOT NULL,
  description VARCHAR(7000) NOT NULL,
  request_moderation BOOLEAN DEFAULT TRUE,
  participant_limit INTEGER DEFAULT 0,
  published_on TIMESTAMP,
  created_on TIMESTAMP NOT NULL,
  category_id BIGINT REFERENCES categories(id) ON DELETE RESTRICT,
  user_id BIGINT REFERENCES users(id) ON DELETE RESTRICT,
  location_id BIGINT REFERENCES locations(id) ON DELETE RESTRICT,
  state TEXT NOT NULL,
  confirmed_requests BIGINT NOT NULL DEFAULT 0,
  views BIGINT
);

CREATE TABLE IF NOT EXISTS compilations_events (
  compilations_id BIGINT REFERENCES compilations(id) ON DELETE CASCADE,
  event_id BIGINT REFERENCES events(id) ON DELETE CASCADE,
  PRIMARY KEY (compilations_id, event_id)
);

CREATE TABLE IF NOT EXISTS requests(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created TIMESTAMP NOT NULL,
  event_id BIGINT REFERENCES events(id) NOT NULL,
  requester_id BIGINT REFERENCES users(id) NOT NULL,
  status TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS comments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  author_id BIGINT REFERENCES users(id) NOT NULL,
  event_id BIGINT REFERENCES events(id) NOT NULL,
  published_time TIMESTAMP NOT NULL,
  text TEXT NOT NULL
);